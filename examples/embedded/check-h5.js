import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright-core'
import { preview } from 'vite'
import config from './src/pocket.config.js'

const root = fileURLToPath(new URL('./', import.meta.url))
// The upgrade check serves two real builds on one origin to keep the same browser storage.
const previousBuild = process.argv[2]
const serve = (outDir, port) => preview({
  root, configFile: false, build: { outDir }, preview: { host: '127.0.0.1', port, strictPort: true },
})
let site = await serve(previousBuild || 'dist/build/h5', 0)
let browser, page
try {
  browser = await chromium.launch()
  page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  page.setDefaultTimeout(7000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const screen = page.locator('uni-page').last()
  const label = text => screen.getByText(text, { exact: true })
  const tab = text => page.locator('uni-tabbar').getByText(text, { exact: true })
  const back = () => screen.locator('[aria-label="返回上一页"]').click()
  const origin = 'http://127.0.0.1:' + site.httpServer.address().port
  await page.goto(origin)
  await label('林溪的路线').waitFor()
  await tab('我的').click()
  await label(config.brand.name).waitFor()
  assert.equal(await screen.getByRole('navigation').count(), 0)
  assert.doesNotMatch(await screen.innerText(), /账户安全|最近活动|演示设置|帮助与反馈|注册/)
  const walk = label('我的步行行程')
  await walk.waitFor()
  const position = await walk.boundingBox()
  assert.ok(position.y > (await screen.locator('.hero').boundingBox()).y)
  assert.ok(position.y < (await label('行程通知').boundingBox()).y)
  await label('编辑资料').click()
  await screen.locator('[aria-label="展示昵称"] input').fill('江舟')
  await label('保存资料').click()
  await label('江舟').waitFor()
  await tab('路线').click()
  await label('江舟的路线').waitFor()

  await tab('我的').click()
  await label('账户设置').click()
  assert.doesNotMatch(await screen.innerText(), /外观|隐私说明|接收通知/)
  await label('通知偏好').click()
  const reminder = screen.locator('uni-switch')
  await reminder.click()
  await page.reload()
  await reminder.waitFor()
  assert.equal(await reminder.locator('.uni-switch-input-checked').count(), 0)
  await page.goto(origin)
  await label(config.brand.name).waitFor()
  await label('河岸晨行').click()
  await label('加入行程').click()
  await label('已加入行程').waitFor()
  if (previousBuild) {
    const port = site.httpServer.address().port
    await site.close()
    site = await serve('dist/build/h5', port)
    await page.goto(origin)
    await label('江舟的路线').waitFor()
    await tab('我的').click()
    await label('江舟').waitFor()
    await label('账户设置').click()
    await label('通知偏好').click()
    await reminder.waitFor()
    assert.equal(await reminder.locator('.uni-switch-input-checked').count(), 0, '升级后应保留已关闭的行程提醒')
    await page.goto(origin)
    await label('河岸晨行').click()
    await label('已加入行程').waitFor()
  }
  await page.goBack()
  await tab('我的').click()
  await label('行程通知').click()
  await label('河岸步道集合地点').waitFor()
  assert.equal(await label('已加入河岸晨行').count(), 0)
  await back()
  await label('账户设置').click()
  await label('退出登录').click()
  await page.getByText('退出', { exact: true }).last().click()
  await label('你好，访客').waitFor()
  await tab('路线').click()
  await label('访客路线').waitFor()
  assert.equal(await screen.locator('.trail-page').evaluate(el => window.getComputedStyle(el).getPropertyValue('--brand')), '',
    '用户中心样式应仅应用于账户页面')
  await label('河岸晨行').click()
  await label('查看集合通知').click()
  await label('去登录').click()
  await label('取消登录').click()
  await label('去登录').click()
  await label('以步道会员登录').click()
  await label('请在南门步道入口集合。').waitFor()
  await page.waitForURL(/uni_modules\/nova-pocket\/pages\/account\/detail/)
  await back()
  await label('查看集合通知').waitFor()
  await page.goBack()
  await label('江舟的路线').waitFor()

  const detail = '/#/pages/account/detail?view=message&id=' + encodeURIComponent('河岸/集合')
  await page.goto(origin + detail)
  await page.reload()
  await label('请在南门步道入口集合。').waitFor()
  await page.waitForURL(/uni_modules\/nova-pocket\/pages\/account\/detail/)
  await back()
  await label('行程通知').waitFor()
  await page.goto(origin + '/#/pages/account/detail?view=security')
  await label('页面不可用').waitFor()
  await label('返回账户中心').click()
  await label('江舟').waitFor()
  // A fresh installation with reminders enabled should receive the host's new message.
  await page.close()
  page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  page.setDefaultTimeout(7000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(origin)
  await page.locator('uni-tabbar').getByText('我的', { exact: true }).click()
  const current = page.locator('uni-page').last()
  await current.getByText('我的步行行程', { exact: true }).click()
  await current.getByText('加入行程', { exact: true }).click()
  await current.getByText('已加入行程', { exact: true }).waitFor()
  await page.goBack()
  await current.getByText('行程通知', { exact: true }).click()
  await current.getByText('已加入河岸晨行', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('宿主 H5 验收通过：原生底栏、会员资料、通知偏好、消息回跳和冷启动回退。')

} catch (error) {
  if (page) console.error(page.url(), await page.locator('body').innerText())
  throw error
} finally {
  await browser?.close()
  await site.close()
}
